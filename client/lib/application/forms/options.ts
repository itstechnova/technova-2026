// Long option lists for the application forms, kept out of the form definitions so those stay
// readable. Option values are the label text itself, so the database stores readable answers.

import type { Option } from "../types";

/** Turns a list of labels into options whose stored value is the label. */
export function toOptions(labels: readonly string[]): Option[] {
  return labels.map((label) => ({ value: label, label }));
}

